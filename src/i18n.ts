export type LocKey = keyof typeof ptBR;

/** Looks up a label and substitutes Valve-style %1$s placeholders. */
export function t(key: LocKey, ...args: (string | number)[]): string {
  let s: string = ptBR[key];
  args.forEach((a, i) => {
    s = s.replace(`%${i + 1}$s`, String(a));
  });
  return s;
}
