const USER_TEMPLATES_KEY = "stories_maker_user_templates_v1";

export function loadUserTemplates(): StoryTemplate[] {
  try {
    const raw = localStorage.getItem(USER_TEMPLATES_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveUserTemplates(templates: StoryTemplate[]): void {
  try {
    localStorage.setItem(USER_TEMPLATES_KEY, JSON.stringify(templates));
  } catch (err) {
    console.error("Falha ao salvar templates do usuário:", err);
  }
}
